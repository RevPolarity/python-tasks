# Begin10. Даны два ненулевых числа. Найти сумму, разность, произведение 
# и частное их квадратов.
a = float(input())
b = float(input())

sq_a = a ** 2
sq_b = b ** 2

sq_sum = sq_a + sq_b
sq_diff = sq_a - sq_b
sq_mult = sq_a * sq_b
sq_div = sq_a / sq_b

print(sq_sum)
print(sq_diff)
print(sq_mult)
print(sq_div)

# --- Знакомство с героем и генерация характеристик -----
print("Как зовут героя?")
hero_name = input()

# Задаем базовые характеристики
health = 100  # Целое число (int) для счета очков здоровья
strength = 15
agility = 12

# Рассчитываем модификатор урона от ловкости (вещественное число float)
# Ловкость дает прирост, но мы делим ее на 10
agility_modifier = agility / 10

# Формула урона: Сила, умноженная на (1 + модификатор ловкости)
raw_damage = strength * (1.0 + agility_modifier)

# Округляем урон до целого числа по правилам банковского округления
damage = round(raw_damage)

print(f"Добро пожаловать, {hero_name}!")
print("Ты входишь в древние соляные копи. Вокруг темно, а в воздухе стоит едкий запах соли.")
print()

# Выводим столбцом характеристики персонажа

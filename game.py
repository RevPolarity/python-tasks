# --- Заголовок -----------------------------------------
title = "СОЛЯНЫЕ ШАХТЫ"
frame = "=" * 19

print(frame)
print("   " + title + "   ")
print(frame)
print()

# --- Знакомство с героем и генерация характеристик -----
print("Как зовут героя?")
hero_name = input()

# Характеристики персонажа
health = 100
strength = 15
agility = 12
stamina = 15  # Запас сил персонажа

agility_modifier = agility / 10
raw_damage = strength * (1.0 + agility_modifier)
damage = round(raw_damage)

print(f"Добро пожаловать, {hero_name}!")
print("Ты входишь в древние соляные копи. Вокруг темно, а в воздухе стоит едкий запах соли.")
print()

# Вывод характеристик
print("--- ХАРАКТЕРИСТИКИ ГЕРОЯ ---")
print(f"Здоровье:   {health} HP")
print(f"Сила:       {strength}")
print(f"Ловкость:   {agility}")
print(f"Запас сил:  {stamina}")
print(f"Урон:       {damage}")
print("----------------------------")
print()

# --- Меню действий -------------------------------------
print("What do you do?") # По условию методички: Что делаешь?
print("1 - осмотреться")
print("2 - идти вперёд")
print("3 - отдохнуть")
print("4 - постучать по стене")
print("5 - собрать кристаллы")
print()

# --- Выбор действия (Логика match/case) ----------------
choice = input()
print()  # Отбивка перед результатом действия

match choice:
    case "1":
        print("Вы осмотрелись. Стены покрыты белыми разводами соли, проход уходит вглубь.")
        
    case "2":
        stamina = stamina - 3
        print("Вы осторожно идёте вперёд. Под вашими сапогами громко хрустит соль.")
        
    case "3":
        stamina = stamina + 2
        print("Вы присели на старый деревянный ящик. Силы постепенно возвращаются.")
        
    case "4":
        # Действие бесплатное, информацию получаем без затрат выносливости
        print("Вы постучали по стене. Эхо глухое, своды шахты кажутся крепкими.")
        
    case "5":
        stamina = stamina - 1
        print("Вы аккуратно откололи от стены горсть чистых соляных кристаллов.")
        
    case _:
        print("Такого действия нет.")

# --- Строка состояния героя ----------------------------
print()  # Отбиваем визуально строку состояния от текста действия
print(f"Здоровье: {health:3d} HP | Запас сил: {stamina:3d}")

# --- Прощание ------------------------------------------
print()
print(frame)
print(f"Удачи в копях, {hero_name}!")
print(frame)

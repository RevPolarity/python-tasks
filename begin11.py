# Begin11. Даны два ненулевых числа. Найти сумму, разность, произведение 
# и частное их модулей.
a = float(input())
b = float(input())

abs_a = abs(a)
abs_b = abs(b)

abs_sum = abs_a + abs_b
abs_diff = abs_a - abs_b
abs_mult = abs_a * abs_b
abs_div = abs_a / abs_b

print(abs_sum)
print(abs_diff)
print(abs_mult)
print(abs_div)
